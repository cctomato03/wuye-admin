-- =============================================================================
-- 000032_merge_company_community_into_tenant : 公司与小区管理并入「租户管理」
--
-- 物业公司 = 租户；小区是租户下的资源。二者均由平台超级管理员在
-- 「系统管理 → 租户管理」里维护（页签：物业公司 / 小区）。
-- 因此删除物业模块里的「公司信息」「小区信息」两个独立菜单及其按钮。
-- =============================================================================

SET NAMES utf8mb4;

UPDATE sys_menu SET deleted = UNIX_TIMESTAMP(NOW(3)) * 1000
WHERE id IN (3150, 3151, 3152, 3153,  -- 物业公司 → 公司信息
             3010, 3011, 3012, 3013, 3014); -- 小区管理 → 小区信息

-- 租户管理菜单文案更准确（这里同时管理物业公司与小区）
UPDATE sys_menu SET name = '物业公司与小区', name_en = 'Companies & Communities',
       remark = '平台侧：物业公司(租户)与小区的新增/编辑/停用'
WHERE id = 1080;
